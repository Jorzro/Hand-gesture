const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const cardDir = path.join(root, "card-images");
const posterDir = path.join(root, "output", "video-posters");
const outputPath = path.join(cardDir, "embedded-media.js");

function dataUrl(filePath, mimeType) {
    return `data:${mimeType};base64,${fs.readFileSync(filePath).toString("base64")}`;
}

const entries = [];

for (let index = 1; index <= 9; index += 1) {
    const name = `card-${String(index).padStart(2, "0")}.jpg`;
    entries.push({
        type: "image",
        url: `./card-images/${name}`,
        previewDataUrl: dataUrl(path.join(cardDir, name), "image/jpeg")
    });
}

for (let index = 1; index <= 3; index += 1) {
    const name = `video-${String(index).padStart(2, "0")}.mp4`;
    const posterName = `${name}.png`;
    entries.push({
        type: "video",
        url: `./card-images/${name}`,
        previewDataUrl: dataUrl(path.join(posterDir, posterName), "image/png")
    });
}

const output = [
    "/* Generated by scripts/generate-embedded-media.cjs. */",
    `window.__WEIMETA_EMBEDDED_MEDIA__ = ${JSON.stringify(entries)};`,
    ""
].join("\n");

fs.writeFileSync(outputPath, output);
console.log(`Generated ${path.relative(root, outputPath)} with ${entries.length} media previews.`);
